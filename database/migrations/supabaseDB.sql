-- ============================================
-- BASE DE DATOS: Sistema de Ventas -
-- ============================================

-- Tipos ENUM personalizados
DROP TYPE IF EXISTS producto_tamano CASCADE;
CREATE TYPE producto_tamano AS ENUM ('pequeño', 'mediano', 'grande', 'unico');

DROP TYPE IF EXISTS pedido_estado CASCADE;
CREATE TYPE pedido_estado AS ENUM ('pendiente', 'en_proceso', 'completado', 'entregado', 'cancelado');

-- ============================================
-- TABLAS PRINCIPALES
-- ============================================

-- Tabla: CATEGORIAS
CREATE TABLE CATEGORIAS (
    id_categoria INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria TEXT NOT NULL UNIQUE,
    descripcion TEXT,
    activo BOOLEAN DEFAULT TRUE
);
CREATE INDEX idx_nombre_categoria ON CATEGORIAS (nombre_categoria);

-- Tabla: PRODUCTOS
CREATE TABLE PRODUCTOS (
    id_producto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_producto TEXT NOT NULL,
    descripcion TEXT,
    precio DECIMAL(10,2) NOT NULL,
    tamano producto_tamano DEFAULT 'unico',
    imagen_url TEXT,
    id_categoria INT NOT NULL,
    activo BOOLEAN DEFAULT TRUE,
    fecha_creacion TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_producto_categoria FOREIGN KEY (id_categoria) REFERENCES CATEGORIAS(id_categoria) ON DELETE RESTRICT
);
CREATE INDEX idx_nombre_producto ON PRODUCTOS (nombre_producto);
CREATE INDEX idx_categoria_producto ON PRODUCTOS (id_categoria);
CREATE INDEX idx_activo_producto ON PRODUCTOS (activo);

-- Tabla: CLIENTES
CREATE TABLE CLIENTES (
    id_cliente INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_cliente VARCHAR(150) NOT NULL,
    telefono VARCHAR(20),
    direccion TEXT,
    notas TEXT,
    activo BOOLEAN DEFAULT TRUE,
    fecha_registro TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_nombre_cliente ON CLIENTES (nombre_cliente);
CREATE INDEX idx_telefono_cliente ON CLIENTES (telefono);

-- Tabla: CANALES_VENTA
CREATE TABLE CANALES_VENTA (
    id_canal INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_canal VARCHAR(50) NOT NULL UNIQUE,
    descripcion VARCHAR(200),
    activo BOOLEAN DEFAULT TRUE
);

-- Tabla: PEDIDOS
CREATE TABLE PEDIDOS (
    id_pedido INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_pedido DATE NOT NULL,
    fecha_limite DATE,
    id_cliente INT NOT NULL,
    id_canal INT NOT NULL,
    subtotal DECIMAL(10,2) NOT NULL DEFAULT 0,
    costo_envio DECIMAL(10,2) DEFAULT 0,
    total DECIMAL(10,2) GENERATED ALWAYS AS (subtotal + COALESCE(costo_envio, 0)) STORED,
    estado pedido_estado DEFAULT 'pendiente',
    metodo_pago VARCHAR(50) DEFAULT 'No especificado',
    requiere_envio BOOLEAN DEFAULT FALSE,
    direccion_envio TEXT,
    notas TEXT,
    fecha_creacion TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pedido_cliente FOREIGN KEY (id_cliente) REFERENCES CLIENTES(id_cliente) ON DELETE RESTRICT,
    CONSTRAINT fk_pedido_canal FOREIGN KEY (id_canal) REFERENCES CANALES_VENTA(id_canal) ON DELETE RESTRICT
);
CREATE INDEX idx_fecha_pedido ON PEDIDOS (fecha_pedido);
CREATE INDEX idx_estado_pedido ON PEDIDOS (estado);
CREATE INDEX idx_cliente_pedido ON PEDIDOS (id_cliente);
CREATE INDEX idx_canal_pedido ON PEDIDOS (id_canal);
CREATE INDEX idx_pedido_fecha_estado ON PEDIDOS(fecha_pedido, estado);


-- Trigger para actualizar fecha_actualizacion
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.fecha_actualizacion = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ language 'plpgsql';

CREATE TRIGGER update_pedidos_updated_at
    BEFORE UPDATE ON PEDIDOS
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

-- Tabla: DETALLE_PEDIDOS
CREATE TABLE DETALLE_PEDIDOS (
    id_detalle INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido INT NOT NULL,
    id_producto INT NOT NULL,
    cantidad INT NOT NULL DEFAULT 1,
    precio_unitario DECIMAL(10,2) NOT NULL,
    subtotal DECIMAL(10,2) GENERATED ALWAYS AS (cantidad * precio_unitario) STORED,
    CONSTRAINT fk_detalle_pedido FOREIGN KEY (id_pedido) REFERENCES PEDIDOS(id_pedido) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto) REFERENCES PRODUCTOS(id_producto) ON DELETE RESTRICT,
    CHECK (cantidad > 0)
);
CREATE INDEX idx_pedido_detalle ON DETALLE_PEDIDOS (id_pedido);
CREATE INDEX idx_producto_detalle ON DETALLE_PEDIDOS (id_producto);
CREATE INDEX idx_detalle_producto_pedido ON DETALLE_PEDIDOS(id_producto, id_pedido);

-- Tabla: GASTOS
CREATE TABLE GASTOS (
    id_gasto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(200) NOT NULL,
    categoria_gasto VARCHAR(100) NOT NULL,
    monto DECIMAL(10,2) NOT NULL,
    fecha_gasto DATE NOT NULL,
    plataforma VARCHAR(50),
    notas TEXT,
    fecha_registro TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CHECK (monto >= 0)
);
CREATE INDEX idx_fecha_gasto ON GASTOS (fecha_gasto);
CREATE INDEX idx_categoria_gasto ON GASTOS (categoria_gasto);
CREATE INDEX idx_gasto_fecha_categoria ON GASTOS(fecha_gasto, categoria_gasto);


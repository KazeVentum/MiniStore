-- Vista: Productos más vendidos
CREATE OR REPLACE VIEW vw_productos_mas_vendidos AS
SELECT 
    pr.id_producto,
    pr.nombre_producto,
    cat.nombre_categoria,
    SUM(dp.cantidad) as total_vendido,
    SUM(dp.subtotal) as ingresos_totales
FROM PRODUCTOS pr
INNER JOIN DETALLE_PEDIDOS dp ON pr.id_producto = dp.id_producto
INNER JOIN PEDIDOS p ON dp.id_pedido = p.id_pedido
INNER JOIN CATEGORIAS cat ON pr.id_categoria = cat.id_categoria
WHERE p.estado != 'cancelado'
GROUP BY pr.id_producto, pr.nombre_producto, cat.nombre_categoria
ORDER BY total_vendido DESC;

-- Vista: Resumen de ganancias
CREATE OR REPLACE VIEW vw_resumen_ganancias AS
WITH ventas_mes AS (
    SELECT 
        TO_CHAR(fecha_pedido, 'YYYY-MM') as mes,
        COUNT(DISTINCT id_pedido) as total_pedidos,
        SUM(total) as ingresos_totales
    FROM PEDIDOS
    WHERE estado != 'cancelado'
    GROUP BY TO_CHAR(fecha_pedido, 'YYYY-MM')
),
gastos_mes AS (
    SELECT 
        TO_CHAR(fecha_gasto, 'YYYY-MM') as mes,
        SUM(monto) as gastos_totales
    FROM GASTOS
    GROUP BY TO_CHAR(fecha_gasto, 'YYYY-MM')
)
SELECT 
    v.mes,
    v.total_pedidos,
    v.ingresos_totales,
    COALESCE(g.gastos_totales, 0) as gastos_totales,
    v.ingresos_totales - COALESCE(g.gastos_totales, 0) as ganancia_neta
FROM ventas_mes v
LEFT JOIN gastos_mes g ON v.mes = g.mes
ORDER BY v.mes DESC;


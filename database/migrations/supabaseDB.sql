-- Funcion: Crear pedido completo
CREATE OR REPLACE FUNCTION sp_crear_pedido(
    p_fecha_pedido DATE,
    p_id_cliente INT,
    p_id_canal INT,
    p_costo_envio DECIMAL(10,2),
    p_requiere_envio BOOLEAN,
    p_direccion_envio TEXT,
    p_notas TEXT
) RETURNS INT AS $$
DECLARE
    v_id_pedido INT;
BEGIN
    INSERT INTO PEDIDOS (
        fecha_pedido, 
        id_cliente, 
        id_canal, 
        costo_envio, 
        requiere_envio, 
        direccion_envio, 
        notas
    ) VALUES (
        p_fecha_pedido,
        p_id_cliente,
        p_id_canal,
        p_costo_envio,
        p_requiere_envio,
        p_direccion_envio,
        p_notas
    ) RETURNING id_pedido INTO v_id_pedido;
    
    RETURN v_id_pedido;
END;
$$ LANGUAGE plpgsql;

-- Funcion: Agregar producto al pedido
CREATE OR REPLACE FUNCTION sp_agregar_producto_pedido(
    p_id_pedido INT,
    p_id_producto INT,
    p_cantidad INT
) RETURNS VOID AS $$
DECLARE
    v_precio DECIMAL(10,2);
BEGIN
    -- Obtener precio actual del producto
    SELECT precio INTO v_precio 
    FROM PRODUCTOS 
    WHERE id_producto = p_id_producto;
    
    -- Insertar detalle
    INSERT INTO DETALLE_PEDIDOS (id_pedido, id_producto, cantidad, precio_unitario)
    VALUES (p_id_pedido, p_id_producto, p_cantidad, v_precio);
    
    -- Actualizar subtotal del pedido
    UPDATE PEDIDOS 
    SET subtotal = (
        SELECT SUM(subtotal) 
        FROM DETALLE_PEDIDOS 
        WHERE id_pedido = p_id_pedido
    )
    WHERE id_pedido = p_id_pedido;
END;
$$ LANGUAGE plpgsql;

-- Funcion: Obtener ventas por rango de días
CREATE OR REPLACE FUNCTION sp_ventas_ultimos_dias(
    p_dias INT
) RETURNS TABLE (
    id_pedido INT,
    fecha_pedido DATE,
    nombre_cliente VARCHAR,
    nombre_canal VARCHAR,
    total DECIMAL,
    estado pedido_estado,
    productos TEXT
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        p.id_pedido,
        p.fecha_pedido,
        c.nombre_cliente,
        cv.nombre_canal,
        p.total,
        p.estado,
        STRING_AGG(
            CONCAT(pr.nombre_producto, ' (', dp.cantidad, ')'),
            ', '
        ) as productos
    FROM PEDIDOS p
    INNER JOIN CLIENTES c ON p.id_cliente = c.id_cliente
    INNER JOIN CANALES_VENTA cv ON p.id_canal = cv.id_canal
    LEFT JOIN DETALLE_PEDIDOS dp ON p.id_pedido = dp.id_pedido
    LEFT JOIN PRODUCTOS pr ON dp.id_producto = pr.id_producto
    WHERE p.fecha_pedido >= (CURRENT_DATE - (p_dias || ' days')::INTERVAL)
      AND p.estado != 'cancelado'
    GROUP BY p.id_pedido, p.fecha_pedido, c.nombre_cliente, cv.nombre_canal, p.total, p.estado
    ORDER BY p.fecha_pedido DESC;
END;
$$ LANGUAGE plpgsql;
